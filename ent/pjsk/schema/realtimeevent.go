package schema

import (
	"time"

	"entgo.io/ent"
	"entgo.io/ent/dialect/entsql"
	"entgo.io/ent/schema"
	"entgo.io/ent/schema/edge"
	"entgo.io/ent/schema/field"
	"entgo.io/ent/schema/index"
)

// RealtimeEvent is one event the realtime (SSE) role delivers to a connected
// Client. The id doubles as the SSE id and replay cursor. Payloads stay in
// Toolbox; a row only carries the reference Cloud renders from.
type RealtimeEvent struct {
	ent.Schema
}

func (RealtimeEvent) Annotations() []schema.Annotation {
	return []schema.Annotation{
		entsql.Annotation{Table: "realtime_events"},
	}
}

func (RealtimeEvent) Fields() []ent.Field {
	return []ent.Field{
		field.Int64("id"),
		field.String("topic").MaxLen(64),
		field.Int("subscription_id"),
		field.String("subscription_version").MaxLen(64),
		// event_id is generated by Toolbox and stored unchanged.
		field.String("event_id").MaxLen(128),
		field.String("payload_ref").MaxLen(512).Default(""),
		field.Bool("empty_result").Default(false),
		field.Time("created_at").Default(time.Now).Immutable(),
		// expires_at is the subscription expiry plus a grace period; GC
		// deletes rows some time after it.
		field.Time("expires_at"),
		field.Int("delivery_count").Default(0),
		field.Time("last_delivered_at").Optional().Nillable(),
		field.Time("acked_at").Optional().Nillable(),
		field.Time("superseded_at").Optional().Nillable(),
		field.String("superseded_reason").MaxLen(32).Default(""),
	}
}

func (RealtimeEvent) Edges() []ent.Edge {
	return []ent.Edge{
		edge.From("subscription", MysekaiBirthdaySubscription.Type).
			Ref("realtime_events").
			Field("subscription_id").
			Unique().
			Required(),
	}
}

func (RealtimeEvent) Indexes() []ent.Index {
	return []ent.Index{
		// Idempotent ingest: a retried notification maps to the same row.
		index.Fields("subscription_id", "subscription_version", "event_id").Unique(),
		// Pending events of one subscription version, in delivery order.
		index.Fields("subscription_id", "subscription_version", "id").
			Annotations(entsql.IndexWhere("acked_at IS NULL AND superseded_at IS NULL")),
		index.Fields("expires_at"),
	}
}
